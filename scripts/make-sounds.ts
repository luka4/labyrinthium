/**
 * Renders the sound set (plan 05). Run: npm run sounds
 *   npm run sounds -- --only step.stone.0   render and encode one id
 *   npm run sounds -- --wav <dir>           also write 32-bit float WAVs there (to listen)
 * Writes assets/sounds/<id>.m4a (AAC, ffmpeg), scripts/sound/sounds.lock.json (hash, duration, peak,
 * rms per id) and src/audio/manifest.ts. ffmpeg is only needed here; the .m4a, the lock and the
 * manifest are committed.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SR, db } from './sound/dsp';
import { RECIPES, VARIANTS, type Recipe } from './sound/recipes';
import { interleave, renderRecipe, statsOf, type SoundStats } from './sound/render';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const OUT = join(root, 'assets', 'sounds');
const LOCK = join(here, 'sound', 'sounds.lock.json');
const MANIFEST = join(root, 'src', 'audio', 'manifest.ts');
const VARIANTS_FILE = join(root, 'src', 'audio', 'variants.ts');
const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;
const wavDir = args.includes('--wav') ? args[args.indexOf('--wav') + 1] : null;

type LockEntry = SoundStats & { bytes: number };

function wavBytes(channels: Float32Array[]): Buffer {
  const data = interleave(channels);
  const head = Buffer.alloc(44);
  head.write('RIFF', 0);
  head.writeUInt32LE(36 + data.length, 4);
  head.write('WAVEfmt ', 8);
  head.writeUInt32LE(16, 16);
  head.writeUInt16LE(3, 20);
  head.writeUInt16LE(channels.length, 22);
  head.writeUInt32LE(SR, 24);
  head.writeUInt32LE(SR * 4 * channels.length, 28);
  head.writeUInt16LE(4 * channels.length, 32);
  head.writeUInt16LE(32, 34);
  head.write('data', 36);
  head.writeUInt32LE(data.length, 40);
  return Buffer.concat([head, data]);
}

function encode(recipe: Recipe, channels: Float32Array[]): number {
  const file = join(OUT, `${recipe.id}.m4a`);
  const kbps = recipe.kbps ?? (channels.length === 2 ? 96 : 56);
  const r = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'f32le', '-ar', String(SR), '-ac', String(channels.length), '-i', 'pipe:0', '-c:a', 'aac', '-b:a', `${kbps}k`, '-ac', String(channels.length), file], { input: interleave(channels), maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(`ffmpeg failed for ${recipe.id}: ${r.stderr?.toString()}`);
  return statSync(file).size;
}

mkdirSync(OUT, { recursive: true });
if (wavDir) mkdirSync(wavDir, { recursive: true });
let lock: Record<string, LockEntry> = {};
try {
  lock = JSON.parse(readFileSync(LOCK, 'utf8'));
} catch {
  lock = {};
}
const t0 = performance.now();
let total = 0;
for (const recipe of RECIPES) {
  if (only && recipe.id !== only) continue;
  const rendered = renderRecipe(recipe);
  const stats = statsOf(rendered);
  const bytes = encode(recipe, rendered.channels);
  if (wavDir) writeFileSync(join(wavDir, `${recipe.id}.wav`), wavBytes(rendered.channels));
  lock[recipe.id] = { ...stats, bytes };
  total += bytes;
}
// stable key order
const ordered: Record<string, LockEntry> = {};
for (const r of RECIPES) if (lock[r.id]) ordered[r.id] = lock[r.id];
writeFileSync(LOCK, JSON.stringify(ordered, null, 1) + '\n');

// the manifest (all ids, in recipe order)
const ids = RECIPES.map((r) => r.id);
const lines: string[] = [];
lines.push(`// GENERATED by scripts/make-sounds.ts (npm run sounds). Do not edit by hand.`);
lines.push(`export type SoundGroup = 'core' | 'game' | 'bed:egypt' | 'bed:exterior';`);
lines.push('');
lines.push(`export type SoundEntry = {`);
lines.push(`  /** bundled asset id (require) */`);
lines.push(`  src: number;`);
lines.push(`  group: SoundGroup;`);
lines.push(`  /** linear gain that puts the sound at its design level, one tile away, before user volume */`);
lines.push(`  gain: number;`);
lines.push(`  /** loop start and end in seconds (the file carries 100 ms of padding on both sides) */`);
lines.push(`  loop?: readonly [number, number];`);
lines.push(`  /** seconds, and channels: for the decoded-memory estimate */`);
lines.push(`  dur: number;`);
lines.push(`  ch: 1 | 2;`);
lines.push(`};`);
lines.push('');
lines.push(`export type SoundId =`);
for (const id of ids) lines.push(`  | '${id}'`);
lines.push(`;`);
lines.push('');
lines.push(`export const SOUNDS: Record<SoundId, SoundEntry> = {`);
for (const r of RECIPES) {
  const e = ordered[r.id];
  if (!e) continue;
  const gainLin = Math.round(db(r.level + 3) * 10000) / 10000;
  const loop = e.loop ? `, loop: [${e.loop[0]}, ${Math.round(e.loop[1] * 10000) / 10000}]` : '';
  lines.push(`  '${r.id}': { src: require('../../assets/sounds/${r.id}.m4a'), group: '${r.group}', gain: ${gainLin}${loop}, dur: ${e.duration}, ch: ${e.channels} },`);
}
lines.push(`};`);
lines.push('');
writeFileSync(MANIFEST, lines.join('\n'));
writeFileSync(
  VARIANTS_FILE,
  `// GENERATED by scripts/make-sounds.ts (npm run sounds). Do not edit by hand.\n// Kept apart from the manifest (which requires the audio files) so tests can import it in Node.\n\n/** base id -> number of variants (files \`<base>.0\` ... \`<base>.n-1\`) */\nexport const VARIANTS: Record<string, number> = ${JSON.stringify(VARIANTS)};\n`,
);
const sizeAll = Object.values(ordered).reduce((a, e) => a + e.bytes, 0);
console.log(`${RECIPES.length} sounds rendered in ${((performance.now() - t0) / 1000).toFixed(1)} s; this run ${(total / 1024).toFixed(0)} KB, set ${(sizeAll / 1024).toFixed(0)} KB (${(sizeAll / 1048576).toFixed(2)} MB)`);
